export type I18nKey = keyof typeof zh;

const dictionaries: Record<'zh' | 'en', Record<I18nKey, string>> = { zh, en };

const locale = ref<'zh' | 'en'>((localStorage.getItem('tiktok-hub-locale') as 'zh' | 'en') || 'zh');

export function useI18n() {
  const t = (key: I18nKey | (string & {}), params?: Record<string, string | number>): string => {
    let text: string = dictionaries[locale.value][key as I18nKey] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
      }
    }
    return text;
  };

  const setLocale = (next: 'zh' | 'en') => {
    locale.value = next;
    localStorage.setItem('tiktok-hub-locale', next);
  };

  const toggleLocale = () => setLocale(locale.value === 'zh' ? 'en' : 'zh');

  return {
    t,
    locale: computed(() => locale.value),
    setLocale,
    toggleLocale,
    keyCount: Object.keys(zh).length,
  };
}
